"""Regenerate en.py, fr.py and rw.py from the shared entries table.

Run ``python3 -m genesis.locales.generate`` after editing any *_i18n.py source.
The generated files are never edited by hand; the parity tests fail if they drift.
"""

import pathlib

from .entries import ENTRIES

HEADER = '"""{title} dictionary, generated by genesis.locales.generate. Do not edit by hand."""\n\n'
LANGUAGES = {"en": ("English", 0), "fr": ("French", 1), "rw": ("Kinyarwanda", 2)}


def render(code):
    name, index = LANGUAGES[code]
    lines = [HEADER.format(title=name), "TRANSLATIONS = {\n"]
    for key in sorted(ENTRIES):
        lines.append(f"    {key!r}: {ENTRIES[key][index]!r},\n")
    lines.append("}\n")
    return "".join(lines)


def write_all(directory=None):
    target = pathlib.Path(directory or pathlib.Path(__file__).parent)
    for code in LANGUAGES:
        (target / f"{code}.py").write_text(render(code), encoding="utf-8")


if __name__ == "__main__":
    write_all()
    print(f"generated {len(ENTRIES)} keys for {', '.join(LANGUAGES)}")
