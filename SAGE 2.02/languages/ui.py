UI_TEXT = {
    "en": ENGLISH,
    "fr": FRENCH,
    "rw": KINYARWANDA,
}


def ui_t(language, key, fallback=None):
    """Return the UI string for language, falling back to English then to the given fallback."""
    table = UI_TEXT.get(language) or {}
    value = table.get(key)
    if value is None:
        value = ENGLISH.get(key)
    if value is None:
        value = fallback
    if value is None:
        value = key
    return value
